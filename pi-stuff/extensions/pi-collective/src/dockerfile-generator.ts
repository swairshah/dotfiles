/**
 * Dockerfile Generator
 * 
 * Generates a Dockerfile that recreates the exact project state
 * at the start of a trajectory. Anyone can build this image and
 * be at the exact point where the trajectory began.
 */

import { readFile, access } from "node:fs/promises";
import { join } from "node:path";

export interface DockerfileConfig {
	repoUrl: string;
	commitSha: string;
	language: string;
	testCommand: string;
	
	// Optional overrides
	baseImage?: string;
	extraDeps?: string[];
	setupCommands?: string[];
}

export interface GeneratedDockerfile {
	dockerfile: string;
	dockerignore: string;
	readme: string;
}

